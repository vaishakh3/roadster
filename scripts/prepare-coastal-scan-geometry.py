"""Offline Blender conversion of Poly Haven Coastal Cliff 01.

Run: blender -b --factory-startup --python scripts/prepare-coastal-scan-geometry.py -- SOURCE_DIR
Source keeps original UVs; collapse decimation produces two LODs. Quantized
geometry is bundled as JavaScript data, so the game needs no model loader.
"""
import base64, json, math, struct, sys
from hashlib import md5
from pathlib import Path
import bpy
from mathutils import Vector

ROOT = Path(__file__).resolve().parents[1]
SOURCE = Path(sys.argv[sys.argv.index('--')+1]).resolve()
OUTPUT = ROOT/'assets/coastal-scan'
OUTPUT.mkdir(parents=True, exist_ok=True)
metadata=json.loads((OUTPUT/'source-files.json').read_text())['gltf']['1k']['gltf']
for name, entry in [('coastal_cliff_01.gltf',metadata)]+list(metadata['include'].items()):
    assert md5((SOURCE/name).read_bytes()).hexdigest()==entry['md5'], f'Source checksum mismatch: {name}'
bpy.ops.object.select_all(action='SELECT')
bpy.ops.object.delete(use_global=False)
bpy.ops.import_scene.gltf(filepath=str(SOURCE/'coastal_cliff_01.gltf'))
source = next(o for o in bpy.context.scene.objects if o.type=='MESH')
source.data.calc_loop_triangles()
original_triangles = len(source.data.loop_triangles)
minima = [-45.055580139160156,-.6500276327133179,-6.205799579620361]
maxima = [46.924373626708984,9.675503730773926,4.760909080505371]
extent = [b-a for a,b in zip(minima,maxima)]
result = {'asset':'Coastal Cliff 01','sourceTriangles':original_triangles,'format':'quantized-p3u16-n3i8-uv2u16-indexu16','bounds':{'min':minima,'max':maxima},'lods':{}}
for key, target in [('near',10000),('far',1500)]:
    obj=source.copy();obj.data=source.data.copy();bpy.context.collection.objects.link(obj)
    bpy.context.view_layer.objects.active=obj
    modifier=obj.modifiers.new('Mobile profile','DECIMATE')
    modifier.ratio=target/original_triangles
    modifier.use_collapse_triangulate=True
    bpy.ops.object.modifier_apply(modifier=modifier.name)
    mesh=obj.data;mesh.calc_loop_triangles()
    uv_layer=mesh.uv_layers.active.data
    normals=mesh.corner_normals
    positions=[];normal_values=[];uv_values=[];indices=[];lookup={}
    for triangle in mesh.loop_triangles:
        for loop_index in triangle.loops:
            vertex=mesh.vertices[mesh.loops[loop_index].vertex_index]
            xyz=obj.matrix_world@vertex.co
            xyz=(xyz.x,xyz.z,-xyz.y)
            n=obj.matrix_world.to_3x3()@normals[loop_index].vector
            n.normalize();n=(n.x,n.z,-n.y)
            uv=uv_layer[loop_index].uv
            pq=tuple(max(0,min(65535,round((xyz[i]-minima[i])/extent[i]*65535))) for i in range(3))
            nq=tuple(max(-127,min(127,round(n[i]*127))) for i in range(3))
            # Native Blender UV coordinates pair with TextureLoader's default flipY.
            uq=tuple(max(0,min(65535,round(uv[i]*65535))) for i in range(2))
            token=pq+nq+uq
            index=lookup.get(token)
            if index is None:
                index=len(positions)//3;lookup[token]=index
                positions.extend(pq);normal_values.extend(nq);uv_values.extend(uq)
            indices.append(index)
    vertices=len(positions)//3
    assert vertices < 65536
    data=struct.pack('<'+'H'*len(positions),*positions)+struct.pack('<'+'b'*len(normal_values),*normal_values)+struct.pack('<'+'H'*len(uv_values),*uv_values)+struct.pack('<'+'H'*len(indices),*indices)
    lod={'vertices':vertices,'triangles':len(indices)//3,'bytes':len(data),'base64':base64.b64encode(data).decode()}
    result['lods'][key]=lod
    bpy.data.objects.remove(obj,do_unlink=True)
    print('LOD',key,vertices,lod['triangles'],len(data))
(OUTPUT/'coastal-cliff-data.js').write_text('// Generated by scripts/prepare-coastal-scan-geometry.py; original CC0 Poly Haven scan.\nexport const coastalCliffData='+json.dumps(result,separators=(',',':'))+';\n')
summary={**result,'lods':{k:{a:b for a,b in v.items() if a!='base64'} for k,v in result['lods'].items()}}
(OUTPUT/'geometry-report.json').write_text(json.dumps(summary,indent=2)+'\n')
print(json.dumps(summary,indent=2))
